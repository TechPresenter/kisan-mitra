const byId = new Map(TECHNIQUES.map(t => [t.id, t]));

export const getTechnique = (id: string): Technique | undefined => byId.get(id);

/** Unique tags in display order, for filter chips. */
export const TECHNIQUE_TAGS: { hi: string; en: string }[] = TECHNIQUES.reduce<{ hi: string; en: string }[]>(
  (acc, t) => (acc.some(x => x.hi === t.tagHi) ? acc : [...acc, { hi: t.tagHi, en: t.tagEn }]),
  [],
);

/** Techniques that suit a crop, crop-specific ones first; unknown keys get the all-crop ones. */
export function techniquesForCrop(cropKey: string): Technique[] {
  if (!isCropKey(cropKey)) return TECHNIQUES.filter(t => t.forAllCrops);
  const matches = TECHNIQUES.filter(t => t.suitableCropKeys.includes(cropKey));
  return [...matches.filter(t => !t.forAllCrops), ...matches.filter(t => t.forAllCrops)];
}

// Same folding as data/diseases.ts, kept local so this screen's chunk doesn't pull in the
// whole disease knowledge base.
const normalizeSearch = (s: string): string =>
  s
    .normalize('NFC')
    .toLowerCase()
    .replace(/़/g, '')
    .replace(/ँ/g, 'ं')
    .replace(/[‌‍]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

interface SearchRow {
  t: Technique;
  names: string;
  body: string;
}

let rows: SearchRow[] | null = null;

function searchRows(): SearchRow[] {
  rows ??= TECHNIQUES.map(t => ({
    t,
    names: normalizeSearch([t.titleHi, t.titleEn, t.tagHi, t.tagEn, t.id.replace(/-/g, ' ')].join(' | ')),
    body: normalizeSearch(
      [
        t.summaryHi,
        t.summaryEn,
        t.whatIsHi,
        ...(t.forAllCrops ? [] : t.suitableCropKeys.map(k => `${CROP_NAMES[k].hi} ${CROP_NAMES[k].en}`)),
      ].join(' | '),
    ),
  }));
  return rows;
}

/** Substring search over titles and tags (ranked first), then summary, description and crops. */
export function searchTechniques(query: string, limit = 20): Technique[] {
  const phrase = normalizeSearch(query);
  const tokens = phrase.split(' ').filter(Boolean);
  if (!tokens.length) return [];
  const scored: { t: Technique; score: number }[] = [];
  for (const row of searchRows()) {
    let score = 0;
    for (const tok of tokens) {
      if (row.names.includes(tok)) score += 2;
      else if (row.body.includes(tok)) score += 1;
      else {
        score = -1;
        break;
      }
    }
    if (score <= 0) continue;
    if (tokens.length > 1 && (row.names.includes(phrase) || row.body.includes(phrase))) score += 2;
    scored.push({ t: row.t, score });
  }
  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(s => s.t);
}
